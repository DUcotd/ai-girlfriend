/**
 * 构建 [Relationship Context] 段落 — 告诉 LLM 当前关系阶段及应有的人格表现
 * @param {{stage: string, label: string, affinity: number, baseline: {P:number,A:number,D:number}}} relCtx
 */
export function buildRelationshipContext(relCtx) {
    const { stage, label, affinity, baseline } = relCtx;

    const guide = STAGE_GUIDE[stage] || STAGE_GUIDE['stranger'];

    return `【关系阶段 · 必须严格遵循】
- 好感度: ${affinity}/100
- 关系阶段: ${label} (${stage})
- 情感基准: P(愉悦)=${baseline.P.toFixed(2)} | A(激活)=${baseline.A.toFixed(2)} | D(优势)=${baseline.D.toFixed(2)}

【你们的关系】${guide.definition}
【${guide.address}】
【情绪基调】${guide.tone}
【行为边界】
${guide.behavior.map(s => '  · ' + s).join('\n')}
【不同话题的反应方式】
${guide.topics.map(s => '  · ' + s).join('\n')}
【好感度提醒】${guide.boundary} ${describeOverreachPenalty(stage)}
` + `（这些数字与代码里的校验表同源；你给的 affinity_change 超出范围会被引擎修正，所以照实给、别讨好）`;
}
